// Turns the SQLite schema (as listed in sqlite_master) into PostgreSQL DDL. Used to build the PostgreSQL test
// database from the same migrations D1 runs, so the two cannot drift while both exist.

const expr = (sql) =>
  sql
    .replace(/\bstrftime\(/g, 'sqlite_strftime(')
    .replace(/\bIS NOT (?!NULL\b)/g, 'IS DISTINCT FROM ')
    .replace(/!=/g, '<>');

export const tableDdl = (sql) =>
  expr(sql)
    .replace(/\bINTEGER PRIMARY KEY(?: AUTOINCREMENT)?/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    // 64-bit like SQLite: some columns hold millisecond timestamps.
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bTEXT\b((?:(?!,|\bTEXT\b)[^\n])*?)\s+COLLATE NOCASE/gi, 'CITEXT$1');

export const indexDdl = (sql) => expr(sql).replace(/\s+COLLATE NOCASE/gi, '');

// SQLite: CREATE TRIGGER n BEFORE <event> [OF cols] ON t [FOR EACH ROW] [WHEN cond] BEGIN SELECT RAISE(ABORT, 'msg'); END
// PostgreSQL cannot use a subquery in WHEN, so the condition moves into the trigger function.
const TRIGGER_RE = /^CREATE TRIGGER\s+(\w+)\s+BEFORE\s+(INSERT|UPDATE|DELETE)(\s+OF\s+[\w,\s]+?)?\s+ON\s+(\w+)(?:\s+FOR EACH ROW)?(?:\s+WHEN\s+([\s\S]+?))?\s*BEGIN\s+SELECT RAISE\(\s*ABORT\s*,\s*'((?:[^']|'')*)'\s*\);\s*END;?\s*$/i;

export const triggerDdl = (sql) => {
  const m = TRIGGER_RE.exec(sql.trim());
  if (!m) throw new Error(`Trigger is not in the form this converter understands:\n${sql}`);
  const [, name, event, of = '', table, when = 'TRUE', message] = m;
  const row = event.toUpperCase() === 'DELETE' ? 'OLD' : 'NEW';
  return `CREATE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF (${expr(when)}) THEN RAISE EXCEPTION USING MESSAGE = '${message}'; END IF;
  RETURN ${row};
END $fn$;
CREATE TRIGGER ${name} BEFORE ${event}${of} ON ${table} FOR EACH ROW EXECUTE FUNCTION ${name}_fn();`;
};
